#!/usr/bin/env bash
# E0 zero-shot matrix (wiki: mimir-graph-benchmark): every cached model, greedy, through vLLM 0.27.1 (eager, as the
# parity gate and the VeRL rollouts), on the test files below (random 1,000-row subsets of the larger ones), named and
# entity-anonymised. Chat models: --style instruct (reason, then an "Answer:" line), thinking off. Base models:
# --style base, 1 shot from the same dataset's train split (KGQA prompts are ~1.3k tokens, the context 4k).
#
#   setsid nohup bash graph_bench/eval/run_e0.sh > $ROOT/e0/queue.log 2>&1 < /dev/null &
#
# One GPU-lock acquisition per model run, so other jobs can slot in between. A finished run (its .json exists) is
# skipped. Do not edit this file while it runs (bash reads scripts incrementally): copy it to a new name instead.
set -uo pipefail
cd /work/dfm/marius-ortega/DFM-HRM-Text
ROOT=${ROOT:-/work/dfm/marius-ortega/dfm-hrm-graphs/mimir_bench}
OUT=$ROOT/e0
LOCK=/work/dfm/marius-ortega/dfm-hrm-graphs/locks/gpu0.lock
PY=/home/ucloud/miniforge3/bin/python
HF=/work/dfm/marius-ortega/dfm-hrm-graphs/hf
B=data/graphs/bench
export HF_HUB_OFFLINE=1 OMP_NUM_THREADS=1 MKL_NUM_THREADS=1
mkdir -p $OUT

NAMED="$B/graphqa/test.jsonl $B/metaqa/test.jsonl $B/kqapro/test.jsonl $B/webqsp/test.jsonl $B/clrs/test.jsonl
       $B/graphqa/test_large.jsonl $B/clrs/test_ood.jsonl
       $B/cwq/test.jsonl $B/clutrr/test.jsonl
       $B/graphqa/test_fresh.jsonl $B/metaqa/test_retrieved.jsonl $B/kqapro/test_retrieved.jsonl"
ANON="$B/metaqa/test.jsonl $B/kqapro/test.jsonl $B/webqsp/test.jsonl $B/cwq/test.jsonl"

# name | model | style | max_model_len | extra flags
MODELS="
mimir15|$HF/DFM-Mimir-v1.5-hfview|instruct|4096|
mimir1|$HF/DFM-Mimir-hfview|instruct|4096|
qwen35_4b|Qwen/Qwen3.5-4B|instruct|8192|
qwen25_7b|Qwen/Qwen2.5-7B-Instruct|instruct|8192|
olmo3_7b|allenai/Olmo-3-7B-Instruct|instruct|8192|
gemma4_e4b|google/gemma-4-E4B-it|instruct|8192|
smollm3_3b|HuggingFaceTB/SmolLM3-3B|instruct|8192|
hrm1b|sapientinc/HRM-Text-1B|base|4096|--shots 1 --shots-from $B/e0/shots.jsonl
"

run() {  # name cond model style maxlen extra files...
  local name=$1 cond=$2 model=$3 style=$4 maxlen=$5 extra=$6; shift 6
  local out=$OUT/$name/$cond.json
  [ -f "$out" ] && { echo "=== skip $name $cond"; return; }
  mkdir -p $OUT/$name
  local tokens=1024; [ "$style" = base ] && tokens=128
  local think="--enable-thinking false"; [ "$style" = base ] && think=""
  exec 9>$LOCK; flock 9
  echo "=== $(date '+%F %T') $name $cond (container $(( $(cat /sys/fs/cgroup/memory.current) / 1000000000 )) GB)"
  bash scripts/graphs/mem_guard.sh 48 -- $PY -m graph_bench.eval.eval_vllm --model "$model" --style $style $think \
    --max-tokens $tokens --max-model-len $maxlen --gpu-memory-utilization 0.85 --enforce-eager --limit ${LIMIT:-1000} \
    --n 1 --temperature 0 --pass-k 1 $extra --out $out "$@" > $OUT/$name/$cond.log 2>&1 < /dev/null
  local rc=$?; echo "=== $(date '+%F %T') $name $cond exit $rc"
  exec 9>&-
}

while IFS='|' read -r name model style maxlen extra; do
  [ -z "$name" ] && continue
  run $name named "$model" $style $maxlen "$extra" $NAMED
  run $name anon "$model" $style $maxlen "$extra --anonymize" $ANON
done <<< "$MODELS"
echo "=== $(date '+%F %T') E0 done"
