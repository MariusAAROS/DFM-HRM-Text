#!/usr/bin/env python3
"""Regenerate our release workflow from the pinned llama.cpp upstream jobs."""
import argparse
import re
import subprocess
from pathlib import Path

_ROOT = Path(__file__).resolve().parents[2]


def _render():
    source = _ROOT / 'llama.cpp'
    revision = subprocess.check_output(
        ['git', '-C', str(source), 'rev-parse', 'HEAD'], text=True).strip()
    workflows = source / '.github/workflows'
    upstream = (workflows / 'release.yml').read_text()
    jobs = upstream[upstream.index('  macos-cpu:'):upstream.index('\n# TODO: this build is disabled', upstream.index('  ios-xcode:'))]
    # This is an upstream-provisioned runner, not a standard hosted runner.
    jobs = jobs.replace("          - build: 's390x'\n            os: ubuntu-24.04-s390x\n", '')
    ui = (workflows / 'ui-build.yml').read_text().split('jobs:\n', 1)[1]
    ui = ui.replace('  build:\n', '  ui-build:\n    needs: [check-release]\n', 1)
    ui = ui.replace('${{ inputs.ui_version }}', '${{ needs.check-release.outputs.tag_name }}')
    jobs += '\n' + ui
    jobs = re.sub(r'^( +)fetch-depth: 0\n', lambda m:
                  f'{m[1]}fetch-depth: 0\n{m[1]}repository: schneiderkamplab/llama.cpp\n{m[1]}ref: {revision}\n', jobs, flags=re.M)
    jobs = re.sub(r'(        uses: actions/checkout@v6\n)(?!        with:)',
                  r'\1' + f'        with:\n          repository: schneiderkamplab/llama.cpp\n          ref: {revision}\n', jobs)
    jobs = jobs.replace('      matrix:\n', '      fail-fast: false\n      matrix:\n')
    job_names = re.findall(r'^  ([a-zA-Z0-9_-]+):$', jobs, re.M)
    publisher = (workflows / 'release-publish.yml').read_text()
    steps = publisher[publisher.index('      - name: Download artifacts'):publisher.index('      - name: Attest release artifacts')]
    steps = steps.replace("        if: ${{ steps.check.outputs.should_release == 'true' }}\n", '')
    steps = steps.replace('${{ github.event.workflow_run.id }}', '${{ github.run_id }}')
    steps = steps.replace('${{ steps.tag.outputs.name }}', '${{ needs.check-release.outputs.tag_name }}')
    header = f'''# Generated by native/binaries/sync_upstream_release.py; do not edit by hand.
# Upstream jobs and packaging from llama.cpp {revision}.
name: Mimir llama.cpp binaries
on:
  workflow_dispatch:
    inputs:
      publish:
        description: Publish completed packages as a GitHub prerelease
        type: boolean
        default: false
cache-mode: write
permissions:
  contents: read
  actions: write
concurrency:
  group: llama-upstream-release
  cancel-in-progress: false
env:
  GH_TOKEN: ${{{{ github.token }}}}
  CMAKE_ARGS: "-DLLAMA_BUILD_EXAMPLES=OFF -DLLAMA_BUILD_TESTS=OFF -DLLAMA_BUILD_TOOLS=ON -DLLAMA_BUILD_SERVER=ON -DGGML_RPC=ON"
jobs:
  check-release:
    runs-on: ubuntu-latest
    outputs:
      should_release: 'true'
      tag_name: mimir-{revision[:9]}
    steps:
      - run: echo 'Building llama.cpp {revision}'
'''
    publish = '''
  publish:
    needs: [check-release, ''' + ', '.join(job_names) + ''']
    runs-on: ubuntu-latest
    permissions:
      actions: read
      contents: write
    steps:
''' + steps + f'''
      - name: Record source and checksums
        env:
          SOURCE_SHA: {revision}
        run: |
          printf '%s\\n' "llama.cpp source: https://github.com/schneiderkamplab/llama.cpp/commit/$SOURCE_SHA" "Packaging workflow: $GITHUB_SHA" > release/SOURCE.txt
          (cd release && sha256sum *.zip *.tar.gz SOURCE.txt > SHA256SUMS)
      - uses: actions/upload-artifact@v7
        with:
          name: release-packages
          path: release/*
      - name: Publish verified build outputs
        if: inputs.publish
        env:
          GH_REPO: ${{{{ github.repository }}}}
          TAG: ${{{{ needs.check-release.outputs.tag_name }}}}
        run: |
          cat > notes.md <<'NOTES'
          Standalone llama.cpp tools with Mimir PrefixLM and opt-in MixedLM support. No model weights or app installers.

          Source: https://github.com/schneiderkamplab/llama.cpp/commit/{revision}

          Uses upstream platform/backend packaging, including CPU fallback in Windows accelerator archives and separate CUDA runtime archives. Download the matching runtime archive when required. Drivers and supported hardware are still required. Snapdragon packages target compatible Qualcomm devices, not arbitrary ARM64 machines.

          CPU and Apple Metal PrefixLM/MixedLM have been tested separately; Linux CPU Release and AddressSanitizer qualification passed. Other accelerator packages are build outputs, not claims of hardware-qualified PrefixLM/MixedLM inference. The known strict Metal flash-attention reference tolerance discrepancy remains documented in the integration report.

          Use the model's embedded chat template: `llama-cli -m model.gguf --attention prefix-lm`. The local `llama-server` offers an OpenAI-compatible API without using OpenAI services. These standalone tools follow upstream TLS/build defaults; they are separate from the Apple app packages. Binaries are not Developer ID notarized or Authenticode signed.

          Includes macOS, Linux, Windows, Android, Apple XCFramework and web UI packages. Upstream's dedicated s390x runner is unavailable here and is omitted. Consult SOURCE.txt and SHA256SUMS for provenance and integrity.
          NOTES
          if gh release view "$TAG" >/dev/null 2>&1; then
            test "$(gh release view "$TAG" --json isDraft --jq .isDraft)" = true
          else
            gh release create "$TAG" --target "$GITHUB_SHA" --draft --prerelease --title "Mimir-compatible llama.cpp $TAG" --notes-file notes.md
          fi
          gh release upload "$TAG" release/* --clobber
          gh release edit "$TAG" --notes-file notes.md --draft=false --prerelease
'''
    return header + jobs + publish


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    destination = _ROOT / '.github/workflows/llama-binaries.yml'
    content = _render()
    if args.check:
        if destination.read_text() != content:
            raise SystemExit('Workflow is stale; run native/binaries/sync_upstream_release.py')
    else:
        destination.write_text(content)


if __name__ == '__main__':
    main()
